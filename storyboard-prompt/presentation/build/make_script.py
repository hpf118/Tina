import json, sys, os
here = os.path.dirname(os.path.abspath(__file__))
notes = json.load(open(os.path.join(here, "notes.json")))
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "Presentation-Script.md")

total = sum(n["seconds"] for n in notes)
words = sum(len(n["text"].split()) for n in notes)

L = []
L.append("# Transforming Learning Design at Scale: presentation script")
L.append("")
L.append("Team-based, practitioner-governed AI storyboarding tool. LSC Learning Engineering Team.")
L.append("")
L.append(f"Twelve slides, about {words:,} words, planned for {total // 60} minutes {total % 60} seconds at a measured pace. Slides 1 to 4 are unchanged from the earlier deck; slides 5 to 12 are new. The same text is in the speaker notes of each slide.")
L.append("")
L.append("## Timing plan")
L.append("")
L.append("| Slide | Title | Time |")
L.append("|---|---|---|")
for n in notes:
    L.append(f"| {n['slide']} | {n['title']} | {n['seconds']} s |")
L.append(f"| | Total | {total // 60} min {total % 60} s |")
L.append("")
L.append("## Script")
L.append("")
for n in notes:
    L.append(f"### Slide {n['slide']}. {n['title']}  ({n['seconds']} s)")
    L.append("")
    L.append(n["text"])
    L.append("")
L.append("## Handling likely questions")
L.append("")
L.append("- **Which AI model does it run on?** A general-purpose assistant available in our environment. The standard is model-independent by design: everything that matters is in the prompt, so a change of model is a re-validation, not a rewrite.")
L.append("- **Does it replace the instructional designer?** No. The generator drafts, structures, maps and checks; it never decides purpose, accuracy or feasibility. Every unresolved item carries a marker naming the person who decides.")
L.append("- **How do you know the output is correct?** Every learner-facing claim traces to an accessible source or becomes an owned gap. Thirty-seven checks run before delivery, and a storyboard is Developer Ready only when every row is.")
L.append("- **Can we use it?** The standard, the change log and the review method can be shared. What we cannot share yet is a hosted tool, which is the scaling problem on slide 11.")
L.append("- **What would you do with more capacity?** Host the prompt, the standards and the reference libraries once, as a governed agent the whole team and partner units can run, with versions and results tracked.")
L.append("")
open(out, "w").write("\n".join(L))
print("wrote", out, "words", words, "total seconds", total)
